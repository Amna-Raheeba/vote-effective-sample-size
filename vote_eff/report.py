"""Markdown reports for audits and for the headline evaluation."""


def audit_report_markdown(result):
    lines = []
    lines.append("# Self-consistency vote audit")
    lines.append("")
    lines.append("## 1. Probe estimates")
    lines.append("")
    lines.append("- Individual accuracy (p_hat): %.3f" % result.p_hat)
    lines.append("- Error correlation, agreement estimator (rho_hat): %.3f" % result.rho_hat)
    lines.append(
        "- Error correlation, variance estimator: %.3f" % result.rho_hat_variance
    )
    lines.append("- Pairwise agreement: %.3f" % result.agreement)
    lines.append(
        "- Agreement expected under independence: %.3f" % result.independent_agreement
    )
    lines.append(
        "- Share of agreement that is bias-driven: %.1f%%" % (100.0 * result.bias_share)
    )
    lines.append("- Accuracy ceiling at any sample count: %.3f" % result.ceiling)
    lines.append("")
    lines.append("## 2. What the votes are worth")
    lines.append("")
    lines.append(
        "| Samples | Effective votes (n_eff) | Predicted accuracy | Predicted gain "
        "| Naive accuracy | Naive gain |"
    )
    lines.append("|---|---|---|---|---|---|")
    for row in result.rows:
        lines.append(
            "| %d | %.2f | %.3f | %.3f | %.3f | %.3f |"
            % (
                row.n,
                row.n_eff,
                row.pred_accuracy,
                row.pred_gain,
                row.naive_accuracy,
                row.naive_gain,
            )
        )
    lines.append("")
    lines.append("## 3. Recommendation")
    lines.append("")
    lines.append(result.recommendation)
    lines.append("")
    return "\n".join(lines)


def evaluation_summary_markdown(evaluation):
    agg = evaluation["aggregates"]
    cfg = evaluation["config"]
    lines = []
    lines.append("# Evaluation summary")
    lines.append("")
    lines.append(
        "Scenarios: %d (accuracy p in %s, latent bias rho in %s). Probe: %d "
        "cases x %d samples. Realised accuracy from %d simulated cases per "
        "scenario. All data is synthetic, generated by the seeded sampler "
        "with planted shared bias; the ground truth correlation is analytic."
        % (
            agg["n_scenarios"],
            cfg["p_values"],
            cfg["rho_values"],
            cfg["probe_cases"],
            cfg["probe_samples"],
            cfg["realised_cases"],
        )
    )
    lines.append("")
    lines.append("## Aggregate results")
    lines.append("")
    lines.append(
        "- Majority-vote gain prediction MAE, this tool: %.4f" % agg["gain_mae_tool"]
    )
    lines.append(
        "- Majority-vote gain prediction MAE, naive independence: %.4f"
        % agg["gain_mae_naive"]
    )
    lines.append(
        "- Mean signed gain error, this tool: %+.4f (negative = under-promise)"
        % agg["gain_bias_tool"]
    )
    lines.append(
        "- Mean signed gain error, naive: %+.4f (positive = over-promise)"
        % agg["gain_bias_naive"]
    )
    lines.append(
        "- Naive over-promise at high bias (rho_latent >= 0.6): %+.4f accuracy "
        "points of gain that never arrives" % agg["naive_overpromise_high_rho"]
    )
    lines.append(
        "- Mean relative n_eff recovery error at n = 32 (biased scenarios): "
        "%.1f%%" % (100.0 * agg["mean_neff_rel_error_rho_positive"])
    )
    lines.append("")
    lines.append("## Per-scenario detail")
    lines.append("")
    lines.append(
        "| p | rho_latent | rho true | rho hat | n_eff true (32) | n_eff hat (32) "
        "| rel. error |"
    )
    lines.append("|---|---|---|---|---|---|---|")
    for scenario in evaluation["scenarios"]:
        lines.append(
            "| %.2f | %.1f | %.3f | %.3f | %.2f | %.2f | %.1f%% |"
            % (
                scenario["p"],
                scenario["rho_latent"],
                scenario["rho_true"],
                scenario["rho_hat"],
                scenario["neff_true_32"],
                scenario["neff_hat_32"],
                100.0 * scenario["neff_rel_error_32"],
            )
        )
    lines.append("")
    return "\n".join(lines)


def headline_markdown(evaluation):
    agg = evaluation["aggregates"]
    lines = []
    lines.append("# Headline results")
    lines.append("")
    lines.append(
        "Self-consistency votes audited on %d synthetic scenarios with known "
        "planted bias (seeded, analytic ground truth)." % agg["n_scenarios"]
    )
    lines.append("")
    showcase = agg.get("showcase")
    if showcase:
        lines.append(
            "- Showcase (p = %.2f, latent bias %.1f): 32 samples are worth "
            "%.2f independent votes in truth; the audit estimates %.2f from a "
            "48 x 16 probe."
            % (
                showcase["p"],
                showcase["rho_latent"],
                showcase["neff_true_32"],
                showcase["neff_hat_32"],
            )
        )
        lines.append(
            "- At that bias level the realised 32-vote gain is %.3f; this "
            "tool predicts %.3f, the naive independence assumption promises "
            "%.3f."
            % (
                showcase["realised_gain_32"],
                showcase["tool_pred_gain_32"],
                showcase["naive_pred_gain_32"],
            )
        )
    lines.append(
        "- Gain-prediction MAE across all scenarios and target sizes: %.4f "
        "for this tool vs %.4f for the naive independence baseline."
        % (agg["gain_mae_tool"], agg["gain_mae_naive"])
    )
    lines.append(
        "- At high bias (rho_latent >= 0.6) the naive baseline over-promises "
        "by %+.4f accuracy points of gain on average; this tool's overall "
        "signed error is %+.4f."
        % (agg["naive_overpromise_high_rho"], agg["gain_bias_tool"])
    )
    lines.append(
        "- Mean relative error of the recovered n_eff at n = 32, biased "
        "scenarios only: %.1f%%."
        % (100.0 * agg["mean_neff_rel_error_rho_positive"])
    )
    lines.append("")
    lines.append(
        "Caveat: all votes are synthetic, drawn from the tool's own seeded "
        "generative model; the experiment measures estimator recovery and "
        "prediction accuracy under that model, not live LLM behaviour."
    )
    lines.append("")
    return "\n".join(lines)
